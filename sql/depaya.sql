-- ====================================================================
-- DepaYa - base de datos PostgreSQL (esquemas, tablas y datos de ejemplo)
-- ====================================================================
-- Uso: crear la base y ejecutar este script conectado a ella.
--   CREATE DATABASE depaya;
--   psql -U postgres -d depaya -f sql/depaya.sql
-- Si ya existen las tablas, primero ejecutar sql/reiniciar.sql.
-- Las tablas son las mismas que crearía Hibernate (se comprueba con
-- spring.jpa.hibernate.ddl-auto=validate).

SET client_encoding = 'UTF8';   -- para que las tildes se carguen bien desde la consola de Windows

-- ====================================================================
-- 1. ESQUEMAS (uno por servicio)
-- ====================================================================

CREATE SCHEMA IF NOT EXISTS usr;   -- ms-auth
CREATE SCHEMA IF NOT EXISTS dep;   -- ms-departamentos
CREATE SCHEMA IF NOT EXISTS res;   -- ms-reservas
CREATE SCHEMA IF NOT EXISTS pag;   -- ms-pagos

-- ====================================================================
-- 2. TABLAS
-- Sin llaves foráneas entre esquemas: cada servicio es independiente.
-- ====================================================================

-- ms-auth
CREATE TABLE usr.usuario (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre                    VARCHAR(100) NOT NULL,
    apellido                  VARCHAR(100) NOT NULL,
    tipo_documento            VARCHAR(20)  NOT NULL,
    numero_documento          VARCHAR(20)  NOT NULL UNIQUE,
    correo                    VARCHAR(150) NOT NULL UNIQUE,
    telefono                  VARCHAR(15)  NOT NULL,
    password                  VARCHAR(100) NOT NULL,   -- hash BCrypt
    rol                       VARCHAR(20)  NOT NULL
                              CHECK (rol IN ('ADMIN', 'PROPIETARIO', 'INQUILINO')),
    activo                    BOOLEAN      NOT NULL DEFAULT TRUE,
    publicaciones_habilitadas BOOLEAN      NOT NULL DEFAULT TRUE,
    fecha_registro            TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_desactivacion       TIMESTAMP(6)
);

-- ms-departamentos
CREATE TABLE dep.departamento (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_propietario     BIGINT        NOT NULL,   -- usr.usuario.id
    propietario_nombre VARCHAR(200)  NOT NULL,   -- copia del nombre para mostrarlo
    titulo             VARCHAR(200)  NOT NULL,
    descripcion        VARCHAR(2000) NOT NULL,
    distrito           VARCHAR(100)  NOT NULL,
    direccion          VARCHAR(250)  NOT NULL,
    categoria          VARCHAR(30)   NOT NULL,
    latitud            NUMERIC(10,8),
    longitud           NUMERIC(11,8),
    precio_noche       NUMERIC(10,2) NOT NULL,
    capacidad_personas INTEGER       NOT NULL,
    habitaciones       INTEGER       NOT NULL,
    banos              INTEGER       NOT NULL,
    imagen_url         VARCHAR(500)  NOT NULL,
    tiene_piscina      BOOLEAN       NOT NULL DEFAULT FALSE,
    tiene_wifi         BOOLEAN       NOT NULL DEFAULT FALSE,
    admite_mascotas    BOOLEAN       NOT NULL DEFAULT FALSE,
    estado             VARCHAR(20)   NOT NULL DEFAULT 'DISPONIBLE'
                       CHECK (estado IN ('DISPONIBLE', 'OCUPADO', 'MANTENIMIENTO', 'INACTIVO')),
    fecha_publicacion  TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ms-reservas (guarda copia de datos del departamento y de las personas)
CREATE TABLE res.reserva (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_departamento           BIGINT        NOT NULL,   -- dep.departamento.id
    id_inquilino              BIGINT        NOT NULL,   -- usr.usuario.id
    id_propietario            BIGINT        NOT NULL,   -- usr.usuario.id
    departamento_titulo       VARCHAR(200)  NOT NULL,
    distrito                  VARCHAR(100)  NOT NULL,
    categoria                 VARCHAR(30)   NOT NULL,
    imagen_url                VARCHAR(500),
    inquilino_nombre          VARCHAR(200)  NOT NULL,
    inquilino_correo          VARCHAR(150)  NOT NULL,
    propietario_nombre        VARCHAR(200)  NOT NULL,
    fecha_ingreso             DATE          NOT NULL,
    fecha_salida              DATE          NOT NULL,
    noches                    INTEGER       NOT NULL,
    cantidad_huespedes        INTEGER       NOT NULL,
    precio_noche              NUMERIC(10,2) NOT NULL,
    total                     NUMERIC(12,2) NOT NULL,
    estado                    VARCHAR(20)   NOT NULL DEFAULT 'PENDIENTE'
                              CHECK (estado IN ('PENDIENTE', 'CONFIRMADA', 'CANCELADA')),
    estado_reembolso          VARCHAR(20)   NOT NULL DEFAULT 'NO_APLICA'
                              CHECK (estado_reembolso IN ('NO_APLICA', 'PENDIENTE', 'DEVUELTO')),
    metodo_reembolso          VARCHAR(20)
                              CHECK (metodo_reembolso IN ('YAPE', 'PLIN', 'VISA', 'MASTERCARD')),
    fecha_creacion            TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_cancelacion         TIMESTAMP(6),
    fecha_solicitud_reembolso TIMESTAMP(6),
    fecha_limite_reembolso    TIMESTAMP(6),
    fecha_reembolso           TIMESTAMP(6)
);

-- ms-pagos (pago simulado: no se guardan datos de tarjeta)
CREATE TABLE pag.pago (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_reserva                BIGINT        NOT NULL,   -- res.reserva.id
    id_inquilino              BIGINT        NOT NULL,   -- usr.usuario.id
    inquilino_nombre          VARCHAR(200)  NOT NULL,
    inquilino_correo          VARCHAR(150)  NOT NULL,
    id_propietario            BIGINT        NOT NULL,   -- usr.usuario.id
    departamento_titulo       VARCHAR(200)  NOT NULL,
    distrito                  VARCHAR(100)  NOT NULL,
    monto                     NUMERIC(12,2) NOT NULL,   -- total de la reserva
    comision                  NUMERIC(12,2) NOT NULL,   -- parte de DepaYa
    monto_propietario         NUMERIC(12,2) NOT NULL,   -- parte del propietario
    moneda                    VARCHAR(3)    NOT NULL DEFAULT 'PEN',
    metodo                    VARCHAR(20)   NOT NULL
                              CHECK (metodo IN ('YAPE', 'PLIN', 'VISA', 'MASTERCARD')),
    estado                    VARCHAR(25)   NOT NULL DEFAULT 'PROCESANDO'
                              CHECK (estado IN ('PROCESANDO', 'COMPLETADO', 'REEMBOLSO_PENDIENTE', 'REEMBOLSADO', 'CANCELADO')),
    referencia_pasarela       VARCHAR(100),
    metodo_reembolso          VARCHAR(20)
                              CHECK (metodo_reembolso IN ('YAPE', 'PLIN', 'VISA', 'MASTERCARD')),
    fecha_creacion            TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_pago                TIMESTAMP(6),
    fecha_solicitud_reembolso TIMESTAMP(6),
    fecha_limite_reembolso    TIMESTAMP(6),
    fecha_reembolso           TIMESTAMP(6)
);

-- ====================================================================
-- 3. ÍNDICES (opcionales: aceleran los filtros más usados)
-- ====================================================================

CREATE INDEX idx_departamento_propietario ON dep.departamento (id_propietario);
CREATE INDEX idx_departamento_estado      ON dep.departamento (estado);
CREATE INDEX idx_departamento_distrito    ON dep.departamento (distrito);

CREATE INDEX idx_reserva_departamento ON res.reserva (id_departamento, estado);
CREATE INDEX idx_reserva_inquilino    ON res.reserva (id_inquilino);
CREATE INDEX idx_reserva_propietario  ON res.reserva (id_propietario);
CREATE INDEX idx_reserva_ingreso      ON res.reserva (fecha_ingreso);

CREATE INDEX idx_pago_reserva     ON pag.pago (id_reserva);
CREATE INDEX idx_pago_inquilino   ON pag.pago (id_inquilino);
CREATE INDEX idx_pago_propietario ON pag.pago (id_propietario);
CREATE INDEX idx_pago_estado      ON pag.pago (estado);

